// Regenerates supabase/seed.sql from the same fake data that demo mode uses.
// Run with: npm run db:seed:generate
import { writeFileSync } from "node:fs";
import { DEMO_AGENCY, generateDataset, type Clock } from "../src/lib/demo-data";
import { AGENCY_TZ } from "../src/lib/time";

const SQL = "\u0000sql:";
const localToday = `(now() at time zone '${AGENCY_TZ}')::date`;

const sqlClock: Clock = {
  ts: (day, hour, minute) =>
    `${SQL}((${localToday} + ${day}) + time '${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}') at time zone '${AGENCY_TZ}'`,
  date: (day) => `${SQL}(${localToday} + ${day})`,
};

const literal = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "string" && v.startsWith(SQL)) return v.slice(SQL.length);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

function insert(table: string, rows: object[]) {
  if (rows.length === 0) return "";
  const cols = ["agency_id", ...Object.keys(rows[0])];
  const values = rows
    .map((r) => `  (${[literal(DEMO_AGENCY.id), ...Object.values(r).map(literal)].join(", ")})`)
    .join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values};\n\n`;
}

const d = generateDataset(sqlClock);
const out =
  `-- GENERATED by scripts/generate-seed.ts. Do not edit by hand.\n` +
  `-- Fictional demo data only. Dates are relative to the day you run it.\n\n` +
  `insert into public.agencies (id, name) values (${literal(DEMO_AGENCY.id)}, ${literal(DEMO_AGENCY.name)});\n\n` +
  insert("clinicians", d.clinicians) +
  insert("physicians", d.physicians) +
  insert("patients", d.patients) +
  insert("visits", d.visits) +
  insert("physician_orders", d.orders) +
  insert("form_audits", d.audits) +
  `-- Accounts created before this seed ran have no profile yet: add them to the demo agency.\n` +
  `insert into public.staff_profiles (id, agency_id, full_name)\n` +
  `select u.id, ${literal(DEMO_AGENCY.id)}, coalesce(u.raw_user_meta_data ->> 'full_name', split_part(u.email, '@', 1))\n` +
  `from auth.users u\non conflict (id) do nothing;\n`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out);
console.log(`Wrote supabase/seed.sql (${d.patients.length} patients, ${d.visits.length} visits).`);
